/**
 * Normalized activity model.
 *
 * Units used internally everywhere (formatting happens only at display time):
 *   distance  -> metres
 *   time      -> seconds (durations) / epoch milliseconds (timestamps)
 *   speed     -> metres per second
 *   pace      -> seconds per kilometre
 *   elevation -> metres
 */
export type ActivityFormat = 'gpx' | 'tcx' | 'fit';

export interface TrackPoint {
  lat?: number;
  lon?: number;
  /** Elevation in metres. */
  ele?: number;
  /** Epoch milliseconds. */
  time?: number;
  /** Heart rate (bpm). */
  hr?: number;
  /** Running cadence in steps per minute. */
  cad?: number;
  /** Cumulative distance recorded by the device (metres), if the file has it. */
  dist?: number;
}

export interface Lap {
  startTime?: number;
  durationS?: number;
  distanceM?: number;
}

/** Totals declared by the file itself (device summary), kept separate from derived values. */
export interface FileSummary {
  distanceM?: number;
  elapsedS?: number;
  movingS?: number;
  calories?: number;
  elevGainM?: number;
  elevLossM?: number;
  avgHr?: number;
  maxHr?: number;
}

/** User edits to metadata / metric values. Never mutates the source data. */
export interface ActivityOverrides {
  name?: string;
  distanceM?: number;
  movingS?: number;
  elapsedS?: number;
  calories?: number;
  location?: string;
}

export interface Activity {
  id: string;
  source: { format: ActivityFormat; fileName: string; importedAt: number };
  name: string;
  sport: string;
  startTime?: number;
  points: TrackPoint[];
  laps: Lap[];
  fileSummary: FileSummary;
  overrides: ActivityOverrides;
  /** Demonstration data generated by the app rather than imported. */
  isDemo?: boolean;
  /** Non-fatal issues found while importing (shown to the user). */
  warnings: string[];
}

export interface Split {
  index: number;
  /** Length of this split in metres (the last one may be partial). */
  distanceM: number;
  durationS: number;
  paceSPerKm: number;
  elevDeltaM: number | null;
}

export type MetricKey =
  | 'distance'
  | 'movingTime'
  | 'elapsedTime'
  | 'avgPace'
  | 'avgSpeed'
  | 'maxSpeed'
  | 'bestPace'
  | 'elevGain'
  | 'elevLoss'
  | 'minEle'
  | 'maxEle'
  | 'avgHr'
  | 'maxHr'
  | 'avgCadence'
  | 'calories'
  | 'date'
  | 'startTime'
  | 'name'
  | 'location'
  | 'fastestSplit';

export interface MetricAvailability {
  available: boolean;
  reason?: string;
}

export interface ActivityMetrics {
  distanceM: number | null;
  elapsedS: number | null;
  movingS: number | null;
  avgPaceSPerKm: number | null;
  avgSpeedMps: number | null;
  maxSpeedMps: number | null;
  bestPaceSPerKm: number | null;
  elevGainM: number | null;
  elevLossM: number | null;
  minEleM: number | null;
  maxEleM: number | null;
  avgHr: number | null;
  maxHr: number | null;
  avgCadence: number | null;
  calories: number | null;
  splits: Split[];
  /** Per-point cumulative distance (metres), aligned with activity.points. */
  cumDist: number[];
  /** Source of the distance figure. */
  distanceSource: 'override' | 'device' | 'gps' | 'summary' | 'none';
  availability: Record<MetricKey, MetricAvailability>;
}
